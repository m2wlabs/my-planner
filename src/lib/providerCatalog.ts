export const PROVIDER_CATEGORIES: { id: "all" | ProviderCategory; label: string }[] = [
  { id: "all", label: "All" },
  { id: "major", label: "Major" },
  { id: "cloud", label: "Cloud & Routers" },
  { id: "fast", label: "Fast Inference" },
  { id: "local", label: "Local & Custom" },
];

export function findCatalogEntry(catalogId?: string, kind?: AiProviderKind): ProviderCatalogEntry | undefined {
  if (catalogId) {
    const exact = PROVIDER_CATALOG.find((e) => e.catalogId === catalogId);
    if (exact) return exact;
  }
  if (kind && kind !== "openai-compatible") {
    return PROVIDER_CATALOG.find((e) => e.catalogId === kind);
  }
  return PROVIDER_CATALOG.find((e) => e.catalogId === "custom");
}
